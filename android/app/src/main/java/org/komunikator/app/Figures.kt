/** One shape on the 64 × 64 grid: 'c' circle, 'e' ellipse, 'r' rounded rectangle, 'p' path. */
class Shape(
    val kind: Char,
    val n: FloatArray,
    val d: String?,
    val fill: Long?,
    val stroke: Long?,
    val width: Float,
    val evenOdd: Boolean,
)

/** How a part moves: see tools/figures.py. */
class Anim(val kind: String, val period: Int, val amount: Float, val phase: Float)

class Part(val ox: Float, val oy: Float, val rotate: Float, val anim: Anim?, val shapes: List<Shape>)

/** A reaction or sticker figure. The data is generated by tools/figures.py. */
class Figure(val id: String, val name: String, val caption: String, val parts: List<Part>)

/**
 * Draws the figure `id`. Animated, it moves the way the desktop app's SMIL
 * animations do; still, it shows its first frame.
 */
@Composable
fun FigureView(id: String, size: Dp, animate: Boolean = true, label: String? = null) {
    val figure = FIGURES[id] ?: return
    val paths = remember(id) {
        figure.parts.map { part ->
            part.shapes.map { shape ->
                shape.d?.let { d ->
                    PathParser().parsePathString(d).toPath().apply {
                        fillType = if (shape.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero
                    }
                }
            }
        }
    }
    val time by produceState(0L, animate) {
        if (animate) {
            val start = withFrameMillis { it }
            while (true) {
                withFrameMillis { value = it - start }
            }
        }
    }
    val modifier = if (label != null) {
        Modifier.size(size).semantics { contentDescription = label }
    } else {
        Modifier.size(size)
    }
    Canvas(modifier = modifier) {
        val unit = this.size.minDimension / 64f
        scale(unit, unit, pivot = Offset.Zero) {
            figure.parts.forEachIndexed { index, part ->
                drawPart(part, paths[index], time)
            }
        }
    }
}

private fun DrawScope.drawPart(part: Part, paths: List<Path?>, time: Long) {
    val anim = part.anim
    var tx = 0f
    var ty = 0f
    var turn = 0f
    var sx = 1f
    var sy = 1f
    var alpha = 1f
    if (anim != null && anim.period > 0) {
        val p = (((time.toFloat() / anim.period) + anim.phase) % 1f + 1f) % 1f
        val wave = (1 - cos(2 * PI * p).toFloat()) / 2
        when (anim.kind) {
            "bob" -> ty = -anim.amount * wave
            "sway" -> turn = anim.amount * sin(2 * PI * p).toFloat()
            "spin" -> turn = 360f * p
            "pulse" -> {
                sx = 1 + anim.amount * wave
                sy = sx
            }
            "blink" -> sy = when {
                p < 0.9f -> 1f
                p < 0.95f -> 1f - 0.9f * (p - 0.9f) / 0.05f
                else -> 0.1f + 0.9f * (p - 0.95f) / 0.05f
            }
            "shake" -> tx = anim.amount * sin(2 * PI * p * 2.5).toFloat()
            "hop" -> ty = if (p < 0.7f) -anim.amount * sin(PI * p / 0.7).toFloat() else 0f
            "rise" -> {
                ty = -anim.amount * p
                alpha = when {
                    p < 0.15f -> p / 0.15f
                    p < 0.7f -> 1f
                    else -> 1f - (p - 0.7f) / 0.3f
                }
            }
        }
    }
    withTransform({
        translate(part.ox, part.oy)
        rotate(part.rotate + turn, pivot = Offset.Zero)
        translate(tx, ty)
        scale(sx, sy, pivot = Offset.Zero)
        translate(-part.ox, -part.oy)
    }) {
        part.shapes.forEachIndexed { index, shape -> drawShape(shape, paths[index], alpha) }
    }
}

private fun DrawScope.drawShape(shape: Shape, path: Path?, alpha: Float) {
    val styles = buildList<Pair<Color, DrawStyle>> {
        shape.fill?.let { add(Color(it) to Fill) }
        shape.stroke?.let {
            add(Color(it) to Stroke(width = shape.width, cap = StrokeCap.Round, join = StrokeJoin.Round))
        }
    }
    val n = shape.n
    for ((color, style) in styles) {
        when (shape.kind) {
            'c' -> drawCircle(color, radius = n[2], center = Offset(n[0], n[1]), alpha = alpha, style = style)
            'e' -> drawOval(
                color,
                topLeft = Offset(n[0] - n[2], n[1] - n[3]),
                size = Size(n[2] * 2, n[3] * 2),
                alpha = alpha,
                style = style,
            )
            'r' -> drawRoundRect(
                color,
                topLeft = Offset(n[0], n[1]),
                size = Size(n[2], n[3]),
                cornerRadius = CornerRadius(n[4]),
                alpha = alpha,
                style = style,
            )
            else -> if (path != null) drawPath(path, color, alpha = alpha, style = style)
        }
    }
}
